// Deep merge
const mergeDeep = (target, source) => {
    for (const key of Object.keys(source)) {
        if (source[key] instanceof Object && key in target) {
            Object.assign(source[key], mergeDeep(target[key], source[key]))
        }
    }
    Object.assign(target || {}, source)
    return target
}

if (!enLocales.pages.migrationUpload) enLocales.pages.migrationUpload = {};
mergeDeep(enLocales.pages.migrationUpload, missingKeysEn);

if (!arLocales.pages.migrationUpload) arLocales.pages.migrationUpload = {};
mergeDeep(arLocales.pages.migrationUpload, missingKeysAr);

fs.writeFileSync(enPath, JSON.stringify(enLocales, null, 2) + '\n');
fs.writeFileSync(arPath, JSON.stringify(arLocales, null, 2) + '\n');

